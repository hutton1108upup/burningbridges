import test from 'node:test';
import assert from 'node:assert/strict';
import {findWorktreeRestriction} from '../scripts/product-copy-policy.mjs';

test('rejects direct, paraphrased and markup-split worktree exclusions', () => {
  for (const copy of [
    'Firestarter generation is not included.',
    'This site does not offer Thriller Dance generation.',
    'Buying credits does not unlock this scene.',
    'Only the Burning Bridges template is supported.',
    'This page only offers references and previews.',
    'This is a local preview, not a dance generator.',
    'Nicole generation <strong>is not included</strong>.',
    '<td>Local photo preparation</td><td>No video render or download</td>',
  ]) assert.ok(findWorktreeRestriction(copy), copy);
});

test('retains input requirements, pricing, attribution and genuine transaction distinctions', () => {
  for (const copy of [
    'Choose a JPG, PNG or WebP photo up to 10 MB.',
    'The selected video costs 100 credits per generation.',
    'Third-party reference clips are not results generated by Burning Bridges.',
    'These measurements compare purchases; they do not include uploaded photos.',
    'Free account creation does not establish a free video export.',
    'This task failed. Check its status before submitting another attempt.',
  ]) assert.equal(findWorktreeRestriction(copy), undefined, copy);
});
